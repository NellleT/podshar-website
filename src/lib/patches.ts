/**
 * Сортировка числом, а не строкой, и это не педантизм.
 *
 * `'0.20' < '0.3'` в алфавитном порядке — то есть двадцатый патч уехал бы ниже
 * третьего ровно тогда, когда список станет длинным. По той же причине не
 * полагаемся на порядок записей в массиве: дописать строку не туда легко, а
 * заметить, что «последняя версия» на главной показывает не ту, — трудно.
 */
function newestFirst(a: Patch, b: Patch): number {
  const [aMajor, aMinor] = a.version.split('.').map(Number);
  const [bMajor, bMinor] = b.version.split('.').map(Number);
  return bMajor - aMajor || bMinor - aMinor;
}

