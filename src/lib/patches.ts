/**
 * Что менялось на сайте, коротко и по версиям.
 *
 * Живёт в репозитории, а не в базе, по трём причинам. Запись едет в том же
 * коммите, что и код, который она описывает, — разъехаться им негде. База одна
 * на троих, и `prisma migrate` меняет таблицы сразу у всех, то есть ради списка
 * из пятнадцати строк пришлось бы трогать общее. И запись видно в диффе, как
 * любой другой текст сайта.
 *
 * Записи **не переводятся**, в отличие от остального интерфейса. Каталоги
 * next-intl роняют рендер на отсутствующем ключе, а этот список растёт после
 * каждой заметной правки — четыре текста на запись означали бы, что рано или
 * поздно кто-то забудет немецкий и страница на `/de` перестанет открываться.
 * Подписи блока переводятся, сами строки — нет: это журнал, а не интерфейс.
 *
 * Не путать с `PatchNote` в `prisma/schema.prisma` — там патчи Dota и Brawl
 * Stars, у них есть поле `game`, и к сайту они отношения не имеют.
 *
 * Показывается в двух местах: кнопкой на главной (последняя строка и номер) и
 * целиком на `/patches`. Кнопка живёт в `components/Patches.tsx`, страница —
 * в `app/[locale]/(app)/patches`.
 *
 * ## Как добавить патч
 *
 * Одна строка сверху массива. Мелкие правки тоже сюда: у списка своя страница,
 * места хватает. Пропускаем только совсем тривиальное — опечатку, переименование
 * переменной: список отвечает на вопрос «что у нас изменилось», а не дублирует
 * `git log`.
 *
 * Номер — `МАЖОР.МИНОР`, руками. Заметная правка поднимает минор на единицу.
 * Когда мелких патчей накопилось столько, что счёт перестал читаться, или
 * появилось что-то по-настоящему крупное, — новый мажор: 0.20 → 1.0. Решение
 * человеческое, код его не выводит и не проверяет.
 */

export type Patch = {
  /** `МАЖОР.МИНОР`. */
  version: string;
  /** `ГГГГ-ММ-ДД`. */
  date: string;
  /**
   * Хендл на сайте. Именно хендл, а не имя: он переживает переименование в
   * профиле. Ник для показа подтягивается из базы (`getMemberNames`), а если
   * базы нет или хендла в ней не нашлось — покажется `@хендл`.
   */
  author: string;
  /** Одна строка на языке того, кто писал. Без точки в конце. */
  note: string;
};

